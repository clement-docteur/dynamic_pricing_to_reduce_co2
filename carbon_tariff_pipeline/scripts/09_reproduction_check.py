"""Reproduction check: compare a re-run of Clement's original pipeline (in $CARBON_OUT) with the committed outputs in
carbon_tariff_pipeline/outputs/, value by value.

Compared: step2_results.json, step3_results.json (marginal), step3_results_average.json, response_theta.npz,
step3_test_schedules{,_average}.npz; and, if results/reproduction/step1_mac/ exists (Step 1/1b re-run on this machine),
step1_metrics.json, step1b_mef.json, ci_forecasts_2013.npz, mef_2013.npz.
Tolerance: relative 1e-9 for JSON numbers; arrays are reported as max absolute differences.
Output: results/reproduction/reproduction_check.json and .md
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from lib.common import OUT, PIPE, PROJECT, save_json  # noqa: E402

import numpy as np  # noqa: E402

COMMITTED = PIPE / "outputs"
RES = PROJECT / "results" / "reproduction"
REL_TOL = 1e-9


def cmp_json(a, b):
    st = {"values": 0, "mismatches": 0, "max_abs_diff": 0.0, "examples": [], "keys_only_in_committed": [], "keys_only_in_rerun": []}

    def walk(x, y, p):
        if isinstance(x, dict):
            st["keys_only_in_committed"] += [f"{p}/{k}" for k in x if k not in y]
            st["keys_only_in_rerun"] += [f"{p}/{k}" for k in y if k not in x]
            for k in x:
                if k in y:
                    walk(x[k], y[k], f"{p}/{k}")
        elif isinstance(x, list) and isinstance(y, list):
            if len(x) != len(y):
                st["mismatches"] += 1
                st["examples"].append([p, f"len {len(x)}", f"len {len(y)}"])
                return
            for i, (u, v) in enumerate(zip(x, y)):
                walk(u, v, f"{p}[{i}]")
        elif isinstance(x, (int, float)) and isinstance(y, (int, float)) and not isinstance(x, bool):
            st["values"] += 1
            if not (np.isnan(x) and np.isnan(y)):
                d = abs(x - y)
                if d > REL_TOL * max(1.0, abs(x)):
                    st["mismatches"] += 1
                    st["max_abs_diff"] = max(st["max_abs_diff"], d)
                    if len(st["examples"]) < 8:
                        st["examples"].append([p, x, y])
        elif x != y:
            st["mismatches"] += 1
            if len(st["examples"]) < 8:
                st["examples"].append([p, x, y])

    walk(a, b, "")
    return st


def cmp_npz(a, b):
    out = {}
    for k in a.files:
        if k not in b.files:
            out[k] = "missing in re-run"
        elif a[k].dtype.kind in "fiub":
            out[k] = float(np.nanmax(np.abs(a[k].astype(float) - b[k].astype(float)))) if a[k].size else 0.0
        else:
            out[k] = 0.0 if (a[k] == b[k]).all() else "differs"
    return out


def main():
    res = {"rerun_dir": str(Path(OUT).resolve().relative_to(PROJECT)), "committed_dir": str(COMMITTED.relative_to(PROJECT)), "files": {}}
    pairs = [(COMMITTED / f, Path(OUT) / f) for f in ("step2_results.json", "step3_results.json", "step3_results_average.json",
                                                    "response_theta.npz", "step3_test_schedules.npz", "step3_test_schedules_average.npz")]
    mac1 = RES / "step1_mac"
    if mac1.exists():
        pairs += [(COMMITTED / f, mac1 / f) for f in ("step1_metrics.json", "step1b_mef.json", "ci_forecasts_2013.npz", "mef_2013.npz")]
    for c, r in pairs:
        key = str(r.resolve().relative_to(PROJECT))
        if not r.exists():
            res["files"][key] = "not re-run"
            continue
        if c.suffix == ".json":
            res["files"][key] = cmp_json(json.loads(c.read_text(encoding="utf-8")), json.loads(r.read_text(encoding="utf-8")))
        else:
            res["files"][key] = {"max_abs_diff_per_array": cmp_npz(np.load(c, allow_pickle=True), np.load(r, allow_pickle=True))}
    save_json(res, RES / "reproduction_check.json")
    lines = ["# Reproduction check (generated by scripts/09_reproduction_check.py)", "",
             f"Re-run: `{res['rerun_dir']}` (Step 1 inputs = committed) and `results/reproduction/step1_mac` (Step 1/1b re-run "
             f"on this machine) vs committed `{res['committed_dir']}`. JSON tolerance: relative {REL_TOL:g}.", "",
             "| File | Numbers compared | Mismatches | Max abs diff | Notes |", "|---|---|---|---|---|"]
    for k, v in res["files"].items():
        if isinstance(v, str):
            lines.append(f"| `{k}` | - | - | - | {v} |")
        elif "values" in v:
            note = []
            if v["keys_only_in_rerun"]:
                note.append(f"{len(v['keys_only_in_rerun'])} keys only in re-run (newer script version)")
            if v["keys_only_in_committed"]:
                note.append(f"{len(v['keys_only_in_committed'])} keys only in committed")
            if v["examples"]:
                note.append("e.g. " + "; ".join(f"{e[0]}: {e[1]} -> {e[2]}" for e in v["examples"][:3]))
            lines.append(f"| `{k}` | {v['values']} | {v['mismatches']} | {v['max_abs_diff']:.3g} | {' / '.join(note)} |")
        else:
            d = v["max_abs_diff_per_array"]
            mx = max((x for x in d.values() if isinstance(x, float)), default=0.0)
            lines.append(f"| `{k}` | {len(d)} arrays | - | {mx:.3g} | " + ", ".join(f"{a}: {x:.3g}" if isinstance(x, float) else f"{a}: {x}"
                                                                             for a, x in d.items()) + " |")
    (RES / "reproduction_check.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
